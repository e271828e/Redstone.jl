module P4
using Test
include(joinpath(pwd(), "test/repl.jl"))
include(joinpath(pwd(), "test/utils.jl"))
include(joinpath(pwd(), "design/reports/20261105_docstring_audit/probes/A6/common.jl"))
using Logging
# Absolute-anchored discrete
struct Anch <: AbstractComponent; T; τ; end
children_dummy = nothing
anch(T, τ = 0) = Group((; d = TickCounter()); sample_times = (; d = Absolute(Period(T), τ)))
two(T1, T2) = Group((; a = TickCounter(), b = TickCounter()); sample_times = (; a = Absolute(Period(T1)), b = Absolute(Period(T2))))
pl = build(single(Sawtooth(1.0)))
sh(d) = (d.h, d.N_base, d.Δt_base)
println("=== h forms")
for h in (1//10, 1, Period(1//10), Hz(10), 0.1, -1//10, 0, :x, big(1)//10, Int32(1))
    tryit("h=$h", () -> sh(Deployment(pl; h)))
end
tryit("h absent", () -> sh(Deployment(pl)))
println("=== N_base/Δt_base forms")
tryit("default", () -> sh(Deployment(pl; h = 1//10)))
tryit("N_base=3", () -> sh(Deployment(pl; h = 1//10, N_base = 3)))
for dt in (1//5, 1, Period(1//5), Hz(5), 0.2, :nope)
    tryit("Δt_base=$dt", () -> sh(Deployment(pl; h = 1//10, Δt_base = dt)))
end
tryit("not whole multiple", () -> sh(Deployment(pl; h = 1//10, Δt_base = 1//4)))
tryit("disagrees N", () -> sh(Deployment(pl; h = 1//10, Δt_base = 1//5, N_base = 3)))
for n in (0, -1, 1.5, 2.0)
    tryit("N_base=$n", () -> sh(Deployment(pl; h = 1//10, N_base = n)))
end
println("=== divide direction, anchor T=1/10, τ")
a1 = build(anch(1//10))
tryit("Δt=1/100 (divides T, T does not divide Δt)", () -> sh(Deployment(a1; h = 1//100, Δt_base = 1//100)))
tryit("Δt=1/10", () -> sh(Deployment(a1; h = 1//100, Δt_base = 1//10)))
tryit("Δt=1/5 (T divides Δt, Δt does not divide T)", () -> sh(Deployment(a1; h = 1//100, Δt_base = 1//5)))
a2 = build(anch(1//10, 1//40))
tryit("offset Δt=1/20: offset not multiple", () -> sh(Deployment(a2; h = 1//100, Δt_base = 1//20)))
tryit("offset Δt=1/40", () -> sh(Deployment(a2; h = 1//200, Δt_base = 1//40)))
println("=== derive")
tryit("derive, continuous only, no anchor", () -> sh(Deployment(pl; h = 1//10, Δt_base = :derive)))
tryit("derive unanchored", () -> sh(Deployment(build(single(TickCounter())); h = 1//10, Δt_base = :derive)))
tryit("derive anchored", () -> sh(Deployment(a1; h = 1//100, Δt_base = :derive)))
tryit("derive mixed", () -> sh(Deployment(build(Group((; a = TickCounter(), b = TickCounter()); sample_times = (; a = Absolute(Period(1//10))))); h = 1//100, Δt_base = :derive)))
du = Deployment(build(anch(1//10, 1//40)); h = 1//200, Δt_base = :derive)
println("offset utilization: ", sh(du), " warnings ", typeof.(warnings(du)), " rows ", [(r.path,r.anchor,r.D,r.Φ,r.Δt) for r in du.schedule.rows])
tw = Deployment(build(two(1//10, 1//15)); h = 1//300, Δt_base = :derive)
println("two: ", sh(tw), " warnings ", typeof.(warnings(tw)), " rows ", [(r.path,r.D) for r in tw.schedule.rows])
println("=== logs once")
lg = Test.TestLogger(); with_logger(lg) do; Deployment(build(two(1//10, 1//15)); h = 1//300, Δt_base = :derive); end
println([ (r.level, first(string(r.message),60)) for r in lg.logs ])
println("=== one throw")
tryit("many faults", () -> Deployment(pl; h = 0.1, N_base = 0, firing_budget = 0, localization_tol = -1, localization_budget = 0, algorithm = Int))
for (k,v) in ((:algorithm, Int), (:algorithm, RK4{Float64}), (:firing_budget, 1.0), (:localization_tol, 0), (:localization_tol, 1//100), (:localization_budget, 1.5))
    tryit("$k=$v", () -> getfield(Deployment(pl; h = 1//10, k => v), k))
end
println("=== equality")
d1 = Deployment(build(single(Sawtooth(1.0))); h = 1//10); d2 = Deployment(build(single(Sawtooth(2.0))); h = 1//10)
println("same grid, other build: ", d1 == d2, " hash eq ", hash(d1) == hash(d2))
println("other N_base ", d1 == Deployment(pl; h = 1//10, N_base = 2), " other algo ", d1 == Deployment(pl; h=1//10, algorithm = Heun))
println("=== stepper binding")
m = Model(d1); println(typeof(m.exec.stepper), " ", length(m.exec.stepper.x₀))
mh = Model(pl; h = 1//10, algorithm = Heun); println(typeof(mh.exec.stepper))
println(typeof(RK4(Float64, 3)), " ", typeof(Heun(ProbeDual, 2)))
println(Deployment(pl; h = 1//10).algorithm, " default")
println("=== firing budget")
m = Model(single(Chatterer()); h = 1//10, firing_budget = 2); init!(m)
println("flips ", modes(m,"c"), " frame_diag ", typeof(m.frame_diag))
sim = Simulation(single(Chatterer()); h = 1//10, firing_budget = 2); init!(sim); step!(sim; frames = 1)
st = latest(sim).status
println("sim status writers ", [(w.who, w.totals) for w in st.writers])
println("warnings(sim) ", warnings(sim))
println("=== Schedule")
g = Group((; z = TickCounter(), c = Sawtooth(1.0), a = Group((; n = TickCounter(), o = TickCounter()); sample_times = (; n = Relative(2), o = Relative(3, 1))));
          sample_times = (; a = Absolute(Period(1//5))))
d = Deployment(build(g); h = 1//20, Δt_base = 1//10)
println([(r.path, r.anchor, r.D, r.Φ, r.Δt, r.rates) for r in d.schedule.rows])
println("scopes ", [(s.path, s.key, s.anchor, s.D, s.Φ) for s in d.schedule.scopes])
println("=== warnings of model")
println(warnings(Model(d1)))
wc = Group((; a = TickCounter()); input_wires = ())
end
