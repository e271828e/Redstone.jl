function P(label, f)
    r = try f() catch e; e end
    if r isa DiagnosticError
        ds = r.carried isa Vector ? r.carried : [r.carried]
        println(label, " => ", [(nameof(typeof(d)), hasproperty(d, :reason) ? d.reason : nothing, hasproperty(d,:role) ? d.role : nothing) for d in ds])
    else
        println(label, " => ", r)
    end
end
