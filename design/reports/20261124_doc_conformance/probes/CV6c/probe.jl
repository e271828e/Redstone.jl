# 200 discrete PID port under a Dual activation: coupling through the port
using Redstone: Group, Simulation, init!, set, linearize, taps, get_input, get_face
import Redstone: LinearizeDual
for ctor in (PID, DiscretePID)
    try
        c = ctor(; Kp = AsPort(), Ki = 0.25, Kd = 0.1, τd = 0.2, Tt = 2.0)
        m = Group((; controller = c); input_wires = ("r" => "controller/r", "y" => "controller/y", "Kp" => "controller/Kp"),
                  output_wires = ("controller/u" => "u", "controller/u_raw" => "u_raw"))
        sim = Simulation(m; Δt_frame = 1//100)
        init!(sim, set(u = (r = 1.0, y = 0.25, Kp = 1.0)))
        lin = linearize(sim, taps(u = (r = get_input(:r), y = get_input(:y), Kp = get_input(:Kp)),
                                   y = (u = get_face(:u),)))
        println("OK   ", ctor, " D = ", lin.D)
    catch e
        println("ERR  ", ctor, " ", sprint(showerror, e)[1:min(end, 300)])
    end
end
