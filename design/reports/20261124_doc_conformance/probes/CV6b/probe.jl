using Redstone: Group, Simulation, init!, step!, set
late(f) = Group((; s = Source{Float64}(f), c = Integrator()); local_wires = ("s/y" => "c/u",))
tryit("Source later frame", () -> begin
    m = late(t -> t < 0.05 ? 1.0 : 1)
    sim = Simulation(m; Δt_frame = 1//100)
    init!(sim, set())
    for _ in 1:10; step!(sim; t_plus = 1//100); end
    :no_error
end)
