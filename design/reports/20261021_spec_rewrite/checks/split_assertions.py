"""Write units/<U>/verify_phase1.md, the new text's assertions one per
sentence, for the verifier's phase 2. From docs/spec_rewrite:

    python3 checks/split_assertions.py ch12 A

Every sentence of a paragraph, bullet or table cell is an item, numbered V1
onward, with the citations it carries and a (bold) mark where it holds a
bold span. Headings are kept as context. A fenced code block is one item
naming its first line. The list is what the verifier used to write blind;
it replaces the blind read, and the verifier adds any assertion a sentence
holds that the list does not separate.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
from norm import render

CITE = re.compile(r'§\d+(?:\.\d+)?|D-\d{3}|Appendix [A-D]')
ABBR = re.compile(r'\b(e\.g|i\.e|cf|vs|etc|resp|approx|no|fig|eq)\.$', re.I)


def keep_bold(t):
    """Link markup collapsed, code fenced to one span, bold kept as **."""
    t = re.sub(r'\[([^\]]+)\]\(#[^)]*\)', r'\1', t)
    t = re.sub(r'\[([^\]]+)\]\[[^\]]*\]', r'\1', t)
    return t.replace('*', '\0').replace('\0\0', '**').replace('\0', '')


def sentences(text):
    """Split on . ? ! followed by space and an upper-case, quote, bracket,
    code, bold or section start, protecting code spans and abbreviations."""
    codes = []
    def stash(m): codes.append(m.group(0)); return f"\x01{len(codes) - 1}\x01"
    t = re.sub(r'`[^`]*`', stash, text)
    out, cur = [], ""
    for piece in re.split(r'(?<=[.?!])\s+(?=[A-Z"“(\[`*§\x01])', t):
        cur = (cur + " " + piece).strip() if cur else piece
        if ABBR.search(cur.rstrip(')')): continue
        out.append(cur); cur = ""
    if cur: out.append(cur)
    return [re.sub(r'\x01(\d+)\x01', lambda m: codes[int(m.group(1))], s) for s in out]


def items(raw):
    out, block, fence = [], [], None
    for line in raw.split("\n") + [""]:
        if fence is None and line.startswith("```"):
            fence = [line]; continue
        if fence is not None:
            fence.append(line)
            if line.startswith("```") and len(fence) > 1:
                body = [l for l in fence[1:-1] if l.strip()]
                out.append(("code", (body[0] if body else "").strip(), False)); fence = None
            continue
        if line.strip():
            block.append(line); continue
        if not block: continue
        text = "\n".join(block); block = []
        if re.match(r'^#{1,4} ', text):
            out.append(("heading", render(text).strip(), False)); continue
        if all(l.lstrip().startswith("|") for l in text.split("\n")):
            rows = [l for l in text.split("\n") if not re.match(r'^\s*\|[-:| ]+\|\s*$', l)]
            for r in rows[1:]:
                for cell in [c.strip() for c in r.strip().strip("|").split("|") if c.strip()]:
                    for s in sentences(keep_bold(cell)): out.append(("item", s, "**" in s))
            continue
        for part in re.split(r'\n(?=\s*(?:- |\d+\. ))', text):
            flat = re.sub(r'\s+', ' ', keep_bold(part)).strip()
            flat = re.sub(r'^(- |\d+\. )', '', flat)
            for s in sentences(flat): out.append(("item", s, "**" in s))
    return out


def write(root, u):
    raw = open(os.path.join(root, "units", u, "new.md")).read()
    lines = [f"# Unit {u}, phase 1: the new text's assertions, one per sentence",
             f"# Generated by checks/split_assertions.py from units/{u}/new.md.", ""]
    n = 0
    for kind, text, bold in items(raw):
        if kind == "heading":
            lines += ["", text]; continue
        n += 1
        if kind == "code":
            lines.append(f"- V{n} [code block] {text}"); continue
        cites = CITE.findall(text)
        tail = (f" [{', '.join(dict.fromkeys(cites))}]" if cites else "") + (" (bold)" if bold else "")
        lines.append(f"- V{n} {text.replace('**', '')}{tail}")
    out = os.path.join(root, "units", u, "verify_phase1.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {n} items")


if __name__ == "__main__":
    write(os.path.abspath(sys.argv[1]), sys.argv[2])
