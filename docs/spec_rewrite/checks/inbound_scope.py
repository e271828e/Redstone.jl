"""List the claims a chapter's rewrite removed, relocated or changed by
ruling, by old section, for the inbound check. From docs/spec_rewrite:

    python3 checks/inbound_scope.py ch12 > ch12/inbound_scope.md

Reads every unit's inventory.json and deleted.md. A section with no entry
here kept every claim in place, so its inbound rows need only the check
that the section's number and title are unchanged. A section listed here
gets the full read: each of its rows is judged against the claims below.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
from norm import norm

HEAD = re.compile(r'^(#{2,3}) (.+)$', re.M)


def sections(old_raw, u):
    """(heading, normalized text) per ## or ### block of a unit's old text."""
    out, pos, head = [], 0, f"unit {u}, before its first heading"
    for m in HEAD.finditer(old_raw):
        out.append((head, norm(old_raw[pos:m.start()]))); head, pos = m.group(2), m.start()
    out.append((head, norm(old_raw[pos:])))
    return out


def main(root):
    units = [u for u in sorted(os.listdir(os.path.join(root, "units")))
             if os.path.exists(os.path.join(root, "units", u, "inventory.json"))]
    by_sec, order = {}, []
    for u in units:
        old = open(os.path.join(root, "units", u, "old.md")).read()
        secs = sections(old, u)
        inv = json.load(open(os.path.join(root, "units", u, "inventory.json")))
        for c in inv["claims"]:
            where, tag = c.get("where", "new"), c.get("tag", "F")
            if where == "new" and tag not in ("M", "R"):
                continue
            kind = ("deleted" if "deleted" in where else "relocated to " + where if where != "new"
                    else "moved" if tag == "M" else f"changed by {c.get('ruling', 'a ruling')}")
            if kind == "moved" and c["new"] == c["old"]:
                kind = "moved inside the unit"
            sec = next((h for h, t in secs if c["old"] in t), secs[0][0])
            if sec not in by_sec: by_sec[sec] = []; order.append(sec)
            by_sec[sec].append((u, c["id"], kind, c["old"]))
        d = os.path.join(root, "units", u, "deleted.md")
        if os.path.exists(d):
            sec = secs[0][0] if len(secs) == 1 else "(see deleted.md)"
            by_sec.setdefault(f"unit {u}, deleted.md", []).append((u, "-", "deleted by ruling", open(d).read().strip().split("\n", 1)[-1].strip()))
            if f"unit {u}, deleted.md" not in order: order.append(f"unit {u}, deleted.md")
    print("# Inbound scope: claims removed, relocated or changed, by old section\n")
    print("Generated by checks/inbound_scope.py. A section absent here kept every claim in place.\n")
    for sec in order:
        print(f"## {sec}\n")
        for u, cid, kind, old in by_sec[sec]:
            print(f"- [{u} {cid}] {kind}: {old}")
        print()


if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]))
